import os
import json
import requests
from pathlib import Path

token_path = Path("token.json")
token_data = json.loads(token_path.read_text(encoding="utf-8"))
access_token = token_data.get("access_token")

video_path = Path("assets/final/videos/INC-VID-001.mp4")
file_size = video_path.stat().st_size

print(f"Testing Resumable Upload on {video_path.name} ({file_size:,} bytes)...")

# Step 1: Initialize Resumable Upload Session
init_url = "https://www.googleapis.com/upload/youtube/v3/videos?uploadType=resumable&part=snippet,status"
headers = {
    "Authorization": f"Bearer {access_token}",
    "Content-Type": "application/json; charset=UTF-8",
    "X-Upload-Content-Length": str(file_size),
    "X-Upload-Content-Type": "video/mp4",
}
metadata = {
    "snippet": {
        "title": "IncuBrix AI Growth Engine - Verified Test #Shorts",
        "description": "Autonomous AI video generated by IncuBrix.\n\n#Shorts #IncuBrix #AI",
        "tags": ["Shorts", "IncuBrix", "AI"],
        "categoryId": "28",
    },
    "status": {
        "privacyStatus": "public",
        "selfDeclaredMadeForKids": False,
    },
}

init_resp = requests.post(init_url, headers=headers, json=metadata, timeout=30)
print(f"Init Status: {init_resp.status_code}")
if init_resp.status_code != 200:
    print(f"Init Error: {init_resp.text}")
    exit(1)

upload_url = init_resp.headers.get("Location")
print(f"Upload URL obtained: {upload_url[:60]}...")

# Step 2: Upload Video Bytes
upload_headers = {
    "Authorization": f"Bearer {access_token}",
    "Content-Type": "video/mp4",
    "Content-Length": str(file_size),
}

with open(video_path, "rb") as f:
    upload_resp = requests.put(upload_url, headers=upload_headers, data=f, timeout=120)

print(f"Upload Status: {upload_resp.status_code}")
print(f"Response: {upload_resp.text[:400]}")
